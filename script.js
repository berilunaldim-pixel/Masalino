// Seçilen masalın SVG çizimini oluşturur.

function illustration(i){

  return '\<svg viewBox="0 0 100 100" aria-hidden="true">'+drawings[i]+'\</svg>';

}

let current=0,mode='kid',fontSize=19;

const $=id=>document.getElementById(id);

// Arama metnine göre masal kartlarını listeler.

function showCards(){

  const q=$('search').value.toLocaleLowerCase('tr');

  $('grid').replaceChildren();

  let count=0;

  tales.forEach((t,i)=>{

    if(!t.title.toLocaleLowerCase('tr').includes(q))return;

    count++;

    const card=document.createElement('button');

    card.className='card';card.style.setProperty('--c',['#f5d9d3','#e5ebd7','#f7e3c6','#e3d9e8','#f4dfc9','#dce8f3','#e7dce5','#f9e8c6'][i]);

    const art=document.createElement('div');art.className='art';art.innerHTML=illustration(i);art.setAttribute('aria-label',t.title+' simgesi');

    const heading=document.createElement('h3');heading.textContent=t.title;

    card.append(art,heading);card.onclick=()=>openTale(i);$('grid').append(card);

  });

  if(!count){const p=document.createElement('p');p.textContent='Aradığın masal bulunamadı.';$('grid').append(p);}

}

function render(){

  const t=tales[current];

  $('title').textContent=t.title;$('symbol').innerHTML=illustration(current);$('picture').style.setProperty('--c',['#f5d9d3','#e5ebd7','#f7e3c6','#e3d9e8','#f4dfc9','#dce8f3','#e7dce5','#f9e8c6'][current]);$('picture').setAttribute('aria-label',t.title+' simgesi');

  $('story').textContent=t[mode];$('story').style.fontSize=fontSize+'px';

  $('reference').textContent='Kaynak: '+t.source;

  $('kid').style.opacity=mode==='kid'?'1':'.55';$('adult').style.opacity=mode==='adult'?'1':'.55';

  $('kid').setAttribute('aria-pressed',String(mode==='kid'));

  $('adult').setAttribute('aria-pressed',String(mode==='adult'));

}

// Masal okuma ekranını açar.

function openTale(i){

  $('about').style.display='none';$('sources').hidden=true;

  current=(i+tales.length)%tales.length;

  $('grid').style.display='none';$('reader').style.display='block';

  render();$('reader').scrollIntoView();

}

function back(){$('reader').style.display='none';$('grid').style.display='grid';$('about').style.display='none';$('sources').hidden=true;}

$('search').oninput=()=>{back();showCards();};

$('home').onclick=()=>{$('search').value='';back();showCards();$('grid').scrollIntoView();};

$('back').onclick=()=>{back();$('grid').scrollIntoView();};

$('navStories').onclick=e=>{e.preventDefault();back();$('grid').scrollIntoView();};

$('navAbout').onclick=e=>{e.preventDefault();back();$('grid').style.display='none';$('about').style.display='block';$('about').scrollIntoView();};

$('navSources').onclick=e=>{e.preventDefault();back();$('grid').style.display='none';$('sources').hidden=false;$('sources').scrollIntoView();};

